EXCHANGE_RATE_USD_TO_INR = Decimal("94.47")

def inr_to_usd(inr_amount: int) -> Decimal:
    """Convert an integer INR amount to USD rounded to 2 decimal places using standard ROUND_HALF_UP."""
    return (Decimal(inr_amount) / EXCHANGE_RATE_USD_TO_INR).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)

