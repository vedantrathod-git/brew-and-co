from datetime import datetime
from decimal import Decimal
from typing import Optional
from pydantic import BaseModel, ConfigDict, Field


class PaymentConfigResponse(BaseModel):
    """Public Razorpay configuration returned to frontend checkout."""

    key_id: str = Field(..., description="Razorpay public key ID")
    currency: str = Field(default="INR", description="Three-letter ISO currency code")
    razorpay_configured: bool = Field(
        default=True,
        description=(
            "True when real Razorpay test/live credentials are configured. "
            "False when placeholder credentials are still in place — "
            "the frontend should display a 'payment not available' message."
        ),
    )



class PaymentOrderCreateRequest(BaseModel):
    """Request payload to initiate a Razorpay payment order."""

    order_number: str = Field(..., min_length=1, max_length=32, description="Brew & Co. order number")
    qr_token: Optional[str] = Field(default=None, max_length=64, description="Table QR token if dine-in order")
    idempotency_key: Optional[str] = Field(default=None, max_length=64, description="Client idempotency key")


class PaymentOrderCreateResponse(BaseModel):
    """Response containing public checkout parameters for Razorpay SDK."""

    razorpay_order_id: str = Field(..., description="Provider order ID generated by Razorpay")
    amount_paise: int = Field(..., gt=0, description="Order total in paise (smallest currency unit)")
    amount: Decimal = Field(..., gt=0, description="Order total in standard currency unit (INR)")
    currency: str = Field(default="INR", description="Three-letter currency code")
    key_id: str = Field(..., description="Razorpay public key ID")
    order_number: str = Field(..., description="Brew & Co. order number")
    payment_reference: str = Field(..., description="Internal payment reference")


class PaymentVerifyRequest(BaseModel):
    """Payload submitted by frontend checkout after customer completes payment in modal."""

    order_number: str = Field(..., min_length=1, max_length=32, description="Brew & Co. order number")
    qr_token: Optional[str] = Field(default=None, max_length=64, description="Table QR token if dine-in")
    razorpay_order_id: str = Field(..., min_length=1, max_length=64, description="Razorpay order ID")
    razorpay_payment_id: str = Field(..., min_length=1, max_length=64, description="Razorpay payment ID")
    razorpay_signature: str = Field(..., min_length=1, max_length=128, description="HMAC SHA-256 signature")


class PaymentVerifyResponse(BaseModel):
    """Response returned after server-side signature verification."""

    success: bool
    payment_status: str
    payment_reference: str
    order_number: str
    message: str


class PaymentPublicStatusResponse(BaseModel):
    """Publicly safe payment status response for QR table guests."""

    order_number: str
    payment_status: str
    payment_method: Optional[str] = None
    amount: Decimal
    currency: str
    payment_reference: Optional[str] = None
    verified_at: Optional[datetime] = None

    model_config = ConfigDict(from_attributes=True)


class PaymentStaffResponse(BaseModel):
    """Detailed payment representation for staff POS audit."""

    id: int
    order_id: int
    payment_reference: str
    provider: str
    provider_order_id: Optional[str] = None
    provider_payment_id: Optional[str] = None
    amount: Decimal
    amount_paise: int
    currency: str
    status: str
    method: Optional[str] = None
    verified_at: Optional[datetime] = None
    error_code: Optional[str] = None
    error_description: Optional[str] = None
    created_at: datetime
    updated_at: datetime

    model_config = ConfigDict(from_attributes=True)
